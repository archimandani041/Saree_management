/**
 * Translation lookup helper function
 * Supports dot notation: t('dashboard.title')
 * Falls back to English if key or locale is missing
 */
export function getTranslation(lang, path, fallback = '') {
  if (!path) return fallback;

  const activeLang = translations[lang] ? lang : 'en';
  const parts = path.split('.');

  let current = translations[activeLang];
  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      current = undefined;
      break;
    }
  }

  if (current !== undefined) return current;

  // Fallback to English
  let enCurrent = translations.en;
  for (const part of parts) {
    if (enCurrent && typeof enCurrent === 'object' && part in enCurrent) {
      enCurrent = enCurrent[part];
    } else {
      enCurrent = undefined;
      break;
    }
  }

  return enCurrent !== undefined ? enCurrent : (fallback || path);
}
